# Step 1: Set up two numbers for operator examples.
a = 10
b = 3

# Step 2: Arithmetic operators (+, -, *, /, //, %, **).
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a**b)

# Step 3: Comparison operators (==, !=, >, <, >=, <=).
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

# Step 4: Logical operators (and, or, not).
print("(a > 5) and (b < 5):", (a > 5) and (b < 5))
print("(a < 5) or (b < 5):", (a < 5) or (b < 5))
print("not (a == b):", not (a == b))
